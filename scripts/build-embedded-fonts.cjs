#!/usr/bin/env node
// Regenerates src/lib/embeddedFonts.js: the Latin, Latin Extended, Vietnamese, Cyrillic and Greek subsets of Inter (400, 700) and Source Serif 4 (700) from the @fontsource packages
// (SIL Open Font License 1.1 - redistribution and embedding are permitted), as base64 woff2 inside one @font-face stylesheet.
// Why: the PDF template used system font stacks only, so the file an applicant sent depended on which fonts the headless Chromium
// container happened to have (and the fit calibration was only valid for one answer to that). Embedded, every PDF is set in the
// same faces. The faces are named "DocSans" / "DocSerif" so they can never be confused with an installed font;
// glyphs outside the Latin subset fall through to the system stack that follows them in the font-family list.
//   usage: node scripts/build-embedded-fonts.cjs      (needs network once, for `npm pack`)
const { execSync } = require('child_process')
const fs = require('fs'), os = require('os'), path = require('path')

// Latin covers Western European names; Latin Extended adds Polish, Czech, Hungarian, Turkish, Romanian, Baltic ...; Vietnamese adds its own
// stacked diacritics; Cyrillic (Russian, Ukrainian, Bulgarian, Serbian ...) and Greek complete the alphabets of Europe. CJK, Arabic and Hebrew
// are far too large to embed and keep using the system fonts. Each face carries the subset's unicode-range (read from the package's own CSS) so the browser picks the right file
// per character - without it the last face declared would claim every character and the others would never be used.
const SUBSETS = ['latin', 'latin-ext', 'vietnamese', 'cyrillic', 'greek']
const FACES = []
for (const subset of SUBSETS) {
  FACES.push({ pkg: '@fontsource/inter', prefix: 'inter', subset, family: 'DocSans', weight: 400 })
  FACES.push({ pkg: '@fontsource/inter', prefix: 'inter', subset, family: 'DocSans', weight: 700 })
  FACES.push({ pkg: '@fontsource/source-serif-4', prefix: 'source-serif-4', subset, family: 'DocSerif', weight: 700 })
}
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'ptfonts-'))
const dirs = {}
for (const pkg of [...new Set(FACES.map(f => f.pkg))]) {
  const tgz = execSync(`npm pack ${pkg} --silent`, { cwd: tmp }).toString().trim().split('\n').pop()
  const dir = path.join(tmp, pkg.replace(/\W+/g, '_')); fs.mkdirSync(dir)
  execSync(`tar -xzf ${tgz} -C ${dir}`, { cwd: tmp }); dirs[pkg] = path.join(dir, 'package')
}
// The unicode-range of a subset is in the package's combined CSS for that weight, in the block labelled "/* <prefix>-<subset>-<weight>-normal */".
const rangeOf = f => {
  const sheet = fs.readFileSync(path.join(dirs[f.pkg], `${f.weight}.css`), 'utf8')
  const block = sheet.split('/* ').find(b => b.startsWith(`${f.prefix}-${f.subset}-${f.weight}-normal */`))
  const m = block && /unicode-range:\s*([^;]+);/.exec(block)
  if (!m) throw new Error(`no unicode-range for ${f.pkg} ${f.subset} ${f.weight}`)
  return m[1].trim()
}
const css = FACES.map(f => {
  const b64 = fs.readFileSync(path.join(dirs[f.pkg], 'files', `${f.prefix}-${f.subset}-${f.weight}-normal.woff2`)).toString('base64')
  return `@font-face { font-family: "${f.family}"; font-weight: ${f.weight}; font-style: normal; font-display: block; src: url(data:font/woff2;base64,${b64}) format("woff2"); unicode-range: ${rangeOf(f)} }`
}).join('\n')
fs.writeFileSync(path.join(__dirname, '..', 'src', 'lib', 'embeddedFonts.js'),
  `// GENERATED by scripts/build-embedded-fonts.cjs - do not edit. Inter 400/700 and Source Serif 4 700 (Latin, Latin Extended, Vietnamese, Cyrillic and Greek subsets, SIL OFL 1.1).\nconst FONT_FACE_CSS = ${JSON.stringify(css)}\nmodule.exports = { FONT_FACE_CSS }\n`)
console.log('wrote src/lib/embeddedFonts.js', css.length, 'chars')
